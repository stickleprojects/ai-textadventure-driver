#!/usr/bin/env python3
"""Read an exported game log JSON and use Claude to generate new eval fixtures
from interesting entries (timeouts, loops, empty extractions).

Usage:
    python scripts/generate_evals.py --log game_log.json --out tests/evals/fixtures.py
    python scripts/generate_evals.py --log game_log.json --out tests/evals/fixtures.py --dry-run
"""
import argparse
import ast
import hashlib
import json
import os
import re
import sys


def _is_interesting(entry):
    response = entry.get("response", "")
    return (
        "WARNING" in response
        or "CRITICAL" in response
        or entry.get("loop_detected")
        or entry.get("extracted") == {}
    )


def _ask_claude(action, game_output):
    try:
        import anthropic
    except ImportError:
        print("anthropic package not installed; run: pip install anthropic", file=sys.stderr)
        sys.exit(1)

    api_key = os.environ.get("ANTHROPIC_API_KEY")
    if not api_key:
        print("ANTHROPIC_API_KEY env var not set", file=sys.stderr)
        sys.exit(1)

    client = anthropic.Anthropic(api_key=api_key)
    prompt = f"""You are reviewing structured JSON extracted from a 1987 text adventure game.
Given the raw game output and the action that produced it, write the correct expected values
for these fields: room, exits, objects (inanimate only), npcs (living creatures),
added_to_inventory, learned_spells.
Rules:
- Horses, knights, orcs, guards, men, women are NPCs. Swords, keys, stones, doors are objects.
- added_to_inventory only when game says "Taken." or "You pick up...".
- If a field would be empty, omit it.
Return JSON only. No explanation.

Action: {action}
Game output: {game_output}"""

    message = client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=512,
        messages=[{"role": "user", "content": prompt}],
    )
    text = message.content[0].text.strip()
    match = re.search(r'\{.*\}', text, re.DOTALL)
    if not match:
        return None
    try:
        return json.loads(match.group(0))
    except json.JSONDecodeError:
        return None


def _load_existing_hashes(out_path):
    if not os.path.exists(out_path):
        return set()
    with open(out_path) as f:
        content = f.read()
    hashes = set()
    for m in re.finditer(r'"game_output":\s*"([^"]+)"', content):
        hashes.add(hashlib.md5(m.group(1).encode()).hexdigest())
    return hashes


def _append_fixtures(out_path, new_cases):
    if not os.path.exists(out_path):
        print(f"{out_path} not found", file=sys.stderr)
        sys.exit(1)
    with open(out_path) as f:
        content = f.read()
    tree = ast.parse(content)
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == "EVAL_CASES":
                    insert_at = node.end_lineno
                    lines = content.splitlines()
                    # Find the closing bracket of EVAL_CASES
                    for i in range(insert_at - 1, -1, -1):
                        if "]" in lines[i]:
                            insert_at = i
                            break
                    additions = "\n".join(
                        f"    {json.dumps(c, indent=4)[1:-1].strip().replace(chr(10), chr(10) + '    ')},"
                        for c in new_cases
                    )
                    # Simple approach: write the new cases as a formatted entry before closing ]
                    lines.insert(insert_at, "    # --- auto-generated by generate_evals.py ---")
                    for c in reversed(new_cases):
                        formatted = json.dumps(c, indent=4)
                        formatted = "    " + formatted.replace("\n", "\n    ") + ","
                        lines.insert(insert_at + 1, formatted)
                    with open(out_path, "w") as f:
                        f.write("\n".join(lines))
                    return
    print("Could not find EVAL_CASES list in output file", file=sys.stderr)
    sys.exit(1)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--log", required=True, help="Path to game_log.json")
    parser.add_argument("--out", required=True, help="Path to tests/evals/fixtures.py")
    parser.add_argument("--dry-run", action="store_true", help="Print new cases without writing")
    args = parser.parse_args()

    with open(args.log) as f:
        game_log = json.load(f)

    interesting = [e for e in game_log if _is_interesting(e)]
    print(f"Found {len(interesting)} interesting entries from {len(game_log)} total")

    existing_hashes = _load_existing_hashes(args.out)
    new_cases = []
    for entry in interesting:
        action = entry.get("action", "")
        game_output = entry.get("response", "")
        h = hashlib.md5(game_output.encode()).hexdigest()
        if h in existing_hashes:
            print(f"  skip (duplicate): {action!r}")
            continue
        print(f"  asking Claude about: {action!r} -> {game_output[:60]!r}...")
        expected = _ask_claude(action, game_output)
        if not expected:
            print(f"  Claude returned no usable JSON, skipping")
            continue
        case = {"id": f"auto_{h[:8]}", "action": action, "game_output": game_output, "expected": expected}
        if args.dry_run:
            print(json.dumps(case, indent=2))
        else:
            new_cases.append(case)
            existing_hashes.add(h)

    if not args.dry_run and new_cases:
        _append_fixtures(args.out, new_cases)
        print(f"Wrote {len(new_cases)} new fixture(s) to {args.out}")
    elif not new_cases:
        print("No new fixtures to add.")


if __name__ == "__main__":
    main()
